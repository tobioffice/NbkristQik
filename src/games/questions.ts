/**
 * The seeded question bank.
 *
 * Branch-neutral on purpose: the league is played across every department, so
 * it stays on school-level science, maths, computing and general knowledge.
 * Each row has a stable slug, so seeding is idempotent and a question can be
 * edited in the database without a reseed overwriting it. The bank is grown at
 * 200 questions so a player's daily run can keep drawing ten they have never
 * seen; the exhaustion fallback in `selection.ts` is the signal to add more.
 *
 * The correct option's position is derived from the slug rather than written
 * by hand. That keeps the bank varied without a second thing to get wrong;
 * the database stores the final order and the index.
 */

export interface SeedQuestion {
  slug: string;
  prompt: string;
  options: string[];
  correct: number;
  topic: string;
}

/** Deterministic 32-bit hash, used only to vary the correct option's slot. */
const slotOf = (slug: string): number => {
  let hash = 0;
  for (let index = 0; index < slug.length; index += 1) {
    hash = (hash * 31 + slug.charCodeAt(index)) >>> 0;
  }
  return hash % 4;
};

const q = (
  slug: string,
  prompt: string,
  correct: string,
  wrong: [string, string, string],
  topic: string,
): SeedQuestion => {
  const options = [...wrong];
  const correctIndex = slotOf(slug);
  options.splice(correctIndex, 0, correct);
  return { slug, prompt, options, correct: correctIndex, topic };
};

